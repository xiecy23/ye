  /* ---------------------------------------------------------------------
   * 阶段判定：优先按日志里的完成记录，没记录才回落到日期
   * ------------------------------------------------------------------- */
  function currentPhase(progress) {
    // progress: { phaseIndex: 0, donePhaseExit: false }
    const idx = Math.max(0, Math.min(PHASES.length - 1, (progress && progress.phaseIndex) || 0));
    return PHASES[idx];
  }

  function phaseIndexForWeek(week) {
    const w = Math.max(1, Math.min(8, week));
    for (let i = 0; i < PHASES.length; i++) {
      const [a, b] = PHASES[i].weeks;
      if (w >= a && w <= b) return i;
    }
    return 0;
  }

  /**
   * 把问卷答案编译成一份目标卡
   */
  function derive(answers) {
    const pain = PAINS.find(p => p.id === answers.pain) || PAINS[3];
    const freq = FREQ.find(f => f.id === Number(answers.freq)) || FREQ[2];
    const sess = SESSION.find(s => s.id === answers.session) || SESSION[1];

    // 训练日间隔：days 越多，间隔越短，但永远不出现连续 3 天
    const restDays = freq.days;

    return {
      pain: pain.id,
      short: pain.short,
      title: pain.label,
      statement: `8 周内改善「${pain.label}」，每周 ${freq.days} 次、每次约 ${sess.minutes} 分钟的固定器械训练`,
      why: pain.why,
      focus: pain.focus,
      metrics: pain.metrics,
      caution: pain.caution,
      freq: freq,
      session: sess,
      totalSessions: freq.days * 8,
      minPass: '每周至少出勤 ' + Math.max(1, freq.days - 1) + ' 次就算达标（不是 ' + freq.days + ' 次）',
      scheduleNote: buildSchedule(freq.days),
      phase: PHASES[0],
      forbidden: FORBIDDEN
    };
  }

  /** 把训练日均匀铺开，保证任意两个训练日之间至少隔一天 */
  function buildSchedule(days) {
    // 1: [三]  2: [一,四]  3: [一,三,五]  4: [一,二,四,五]
    const PATTERN = { 1: [2], 2: [0, 3], 3: [0, 2, 4], 4: [0, 1, 3, 4] };
    const idxs = PATTERN[days] || PATTERN[3];
    const DOW = ['周一', '周二', '周三', '周四', '周五', '周六', '周日'];
    return DOW.map((name, i) => ({
      dow: i,
      name,
      isTraining: idxs.indexOf(i) >= 0,
      label: idxs.indexOf(i) >= 0
        ? '训练日'
        : (i === 5 || i === 6) ? '休息 / 可选拉伸'
        : '恢复日 · 只做拉伸就够'
    }));
  }

